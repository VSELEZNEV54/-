export const articleBySlug = (slug: string) => articles.find((a) => a.slug === slug)
export const articlesByCategory = (c: ArticleCategory) => articles.filter((a) => a.category === c)
export const articlesForCar = (slug: string) => articles.filter((a) => a.relatedCars?.includes(slug))
export const articlesForTariff = (slug: string) => articles.filter((a) => a.relatedTariffs?.includes(slug))

export function articleWords(a: Article) {
  let words = a.lead.split(/\s+/).length
  for (const b of a.blocks) {
    if (b.type === 'p' || b.type === 'h2' || b.type === 'quote') words += b.text.split(/\s+/).length
    else if (b.type === 'list') words += b.items.join(' ').split(/\s+/).length
    else if (b.type === 'callout') words += (b.text + ' ' + (b.title ?? '')).split(/\s+/).length
    else if (b.type === 'table') words += b.rows.flat().join(' ').split(/\s+/).length
    else if (b.type === 'faq') words += b.items.map((i) => i.q + ' ' + i.a).join(' ').split(/\s+/).length
  }
  return words
}

export const relatedArticles = (a: Article, n = 3) =>
  articles.filter((x) => x.slug !== a.slug).sort((x, y) => (x.category === a.category ? -1 : 0) - (y.category === a.category ? -1 : 0)).slice(0, n)
